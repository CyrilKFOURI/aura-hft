"""One-command OBI backtest: `python -m research.obi_backtest [--itch FILE]`.

1. Extracts per-symbol event arrays with the golden model (cached as .npz).
2. Runs the parameter grid (threshold x horizon x latency) per symbol.
3. Writes research/obi_backtest/results/results.json and results.md.
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
import time
from pathlib import Path

from .backtest import (NS, OPEN_NS, Config, literal_hardware_orders, run_mid_to_mid, run_strategy,
                       summarize, summarize_mid)
from .extract import extract, load, out_path
from .model import Costs, RiskConfig

ROOT = Path(__file__).resolve().parents[2]
RESULTS = Path(__file__).resolve().parent / "results"
SYMBOLS = ["AAPL", "MSFT", "TSLA", "QQQ"]
THRESHOLDS = [0.2, 0.4, 0.6]
HORIZONS_S = [1, 10, 60]
LATENCIES_NS = [0, 1_000, 10_000, 100_000]
REF_LATENCY_NS = 1_000  # "hardware-like" reaction delay used in the headline tables


def default_itch() -> Path:
    files = sorted((ROOT / "data" / "cache").glob("01302019.NASDAQ_ITCH50*.itch"), key=lambda p: p.stat().st_size)
    if not files:
        raise SystemExit("no ITCH file in data/cache: run `python data/fetch.py --messages 60000000` first")
    return files[-1]


def hhmm(ns: int) -> str:
    s = ns // NS
    return f"{s // 3600:02d}:{s % 3600 // 60:02d}:{s % 60:02d}"


def fmt(x: float, nd: int = 2) -> str:
    return "n/a" if x != x else f"{x:,.{nd}f}"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--itch", type=Path, default=None)
    ap.add_argument("--symbols", nargs="+", default=SYMBOLS)
    ap.add_argument("--re-extract", action="store_true")
    args = ap.parse_args()
    itch = args.itch or default_itch()
    print(f"ITCH file: {itch}")

    missing = [s for s in args.symbols if args.re_extract or not out_path(itch, s).exists()]
    if missing:
        extract(itch, missing)
    events = {s: load(out_path(itch, s)) for s in args.symbols}

    costs, risk = Costs(), RiskConfig()
    results: list[dict] = []
    started = time.time()
    for th, h, lat in itertools.product(THRESHOLDS, HORIZONS_S, LATENCIES_NS):
        cfg = Config(threshold=th, horizon_ns=h * NS, latency_ns=lat)
        pooled = []
        for sym in args.symbols:
            trades, info = run_strategy(sym, events[sym], cfg, costs, risk)
            pooled += trades
            for session in ("pre", "regular"):
                sel = [t for t in trades if t.session == session]
                results.append({"symbol": sym, "session": session, "threshold": th, "horizon_s": h,
                                "latency_ns": lat, **summarize(sel), **{f"run_{k}": v for k, v in info.items()}})
        for session in ("pre", "regular"):
            sel = [t for t in pooled if t.session == session]
            results.append({"symbol": "ALL", "session": session, "threshold": th, "horizon_s": h,
                            "latency_ns": lat, **summarize(sel)})
    mids = []
    for th, h in itertools.product(THRESHOLDS, HORIZONS_S):
        pooled_pts = []
        for sym in args.symbols:
            pooled_pts += run_mid_to_mid(events[sym], Config(threshold=th, horizon_ns=h * NS, latency_ns=0))
        for session in ("pre", "regular"):
            sel = [p for p in pooled_pts if (p[0] >= OPEN_NS) == (session == "regular")]
            mids.append({"symbol": "ALL", "session": session, "threshold": th, "horizon_s": h,
                         **summarize_mid(sel, 100)})
    literal = {}
    tb_risk = RiskConfig(max_cum_notional_raw=5_000_000_000)  # $500k, as in the RTL testbenches
    for sym in args.symbols:
        literal[sym] = literal_hardware_orders(events[sym], 0.4, 100, tb_risk)
    coverage = {s: {"events": int(len(e["ts"])), "first": hhmm(int(e["ts"][0])), "last": hhmm(int(e["ts"][-1]))}
                for s, e in events.items()}
    print(f"grid done in {time.time() - started:,.0f} s")

    RESULTS.mkdir(exist_ok=True)
    payload = {"itch": itch.name, "coverage": coverage, "costs": costs.__dict__, "risk": risk.__dict__,
               "strategy": results, "mid_to_mid": mids, "literal_hardware": literal}
    (RESULTS / "results.json").write_text(json.dumps(payload, indent=1))
    (RESULTS / "results.md").write_text(render(payload), encoding="utf-8")
    print(f"wrote {RESULTS / 'results.md'}")
    return 0


def _pick(rows: list[dict], sym: str, session: str, th: float, h: int, lat: int) -> dict:
    return next(r for r in rows if r["symbol"] == sym and r["session"] == session and r["threshold"] == th
                and r["horizon_s"] == h and r["latency_ns"] == lat)


def render(p: dict) -> str:
    S = p["strategy"]
    out = [f"# Raw results — {p['itch']}", "", "Generated by `python -m research.obi_backtest`. Do not edit by hand.", ""]
    out += ["## Data coverage", "", "| Symbol | Book events | First | Last |", "|:--|--:|:--|:--|"]
    out += [f"| {s} | {c['events']:,} | {c['first']} | {c['last']} |" for s, c in p["coverage"].items()]
    for session in ("pre", "regular"):
        label = "pre-market (04:00–09:30)" if session == "pre" else "regular session (09:30+)"
        out += ["", f"## Strategy, 4 symbols pooled, {label}, 1 µs latency, after costs", "",
                "| Threshold | Horizon | Trades | Hit rate | Gross PnL $/share | Net PnL $/share | Net PnL $ | Max DD $ | 95 % CI net PnL |",
                "|--:|--:|--:|--:|--:|--:|--:|--:|:--|"]
        for th, h in itertools.product(THRESHOLDS, HORIZONS_S):
            a = _pick(S, "ALL", session, th, h, REF_LATENCY_NS)
            out.append(f"| {th} | {h} s | {a['trades']:,} | {fmt(a['hit_rate'] * 100, 1)} % | "
                       f"{fmt(a['gross_per_share'], 4)} | {fmt(a['net_per_share'], 4)} | {fmt(a['net'])} | "
                       f"{fmt(a['max_dd'])} | [{fmt(a['ci_lo'])} ; {fmt(a['ci_hi'])}] |")
    out += ["", "CI: block bootstrap with 5-minute blocks on net PnL aggregated per minute (2000 draws).", ""]
    out += ["## Per symbol (threshold 0.4, horizon 10 s, 1 µs latency)", "",
            "| Symbol | Session | Trades | Hit rate | Net $/share | Net PnL $ | Max DD $ | 95 % CI net PnL | Maker share |",
            "|:--|:--|--:|--:|--:|--:|--:|:--|--:|"]
    for r in S:
        if r["symbol"] != "ALL" and r["threshold"] == 0.4 and r["horizon_s"] == 10 and r["latency_ns"] == REF_LATENCY_NS:
            out.append(f"| {r['symbol']} | {r['session']} | {r['trades']:,} | {fmt(r['hit_rate'] * 100, 1)} % | "
                       f"{fmt(r['net_per_share'], 4)} | {fmt(r['net'])} | {fmt(r['max_dd'])} | "
                       f"[{fmt(r['ci_lo'])} ; {fmt(r['ci_hi'])}] | {fmt(r['maker_share'] * 100, 0)} % |")
    out += ["", "## Latency sensitivity (4 symbols, regular session, threshold 0.4)", "",
            "| Horizon | " + " | ".join(f"{lat // 1000} µs" for lat in LATENCIES_NS) + " |",
            "|--:|" + "--:|" * len(LATENCIES_NS)]
    for h in HORIZONS_S:
        cells = []
        for lat in LATENCIES_NS:
            a = _pick(S, "ALL", "regular", 0.4, h, lat)
            cells.append(f"{fmt(a['net_per_share'], 4)} ({a['trades']})")
        out.append(f"| {h} s | " + " | ".join(cells) + " |")
    out += ["", "Cell: net PnL $/share (number of trades).", ""]
    out += ["## Naive mid-to-mid upper bound (no costs, no queue, no latency)", "",
            "| Session | Threshold | Horizon | Signals | Hit rate | $/share | Total $ (100 shares) | 95 % CI |",
            "|:--|--:|--:|--:|--:|--:|--:|:--|"]
    M = p["mid_to_mid"]
    for session, th, h in itertools.product(("pre", "regular"), THRESHOLDS, HORIZONS_S):
        r = next(r for r in M if r["session"] == session and r["threshold"] == th and r["horizon_s"] == h)
        out.append(f"| {session} | {th} | {h} s | {r['signals']:,} | {fmt(r['hit_rate'] * 100, 1)} % | "
                   f"{fmt(r['per_share'], 4)} | {fmt(r['total'])} | [{fmt(r['ci_lo'])} ; {fmt(r['ci_hi'])}] |")
    out += ["", "## Literal RTL behaviour (threshold 0.4, $500k cumulative cap from the testbenches)", "",
            "| Symbol | Orders emitted (1 per BBO update, limited by tx_busy) | Approved before cumulative cap | Cap reached at |",
            "|:--|--:|--:|:--|"]
    for s, v in p["literal_hardware"].items():
        t = hhmm(v["t_cum_limit_ns"]) if v["t_cum_limit_ns"] else "never"
        out.append(f"| {s} | {v['orders_emitted']:,} | {v['approved_before_cum_limit']:,} | {t} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.exit(main())
